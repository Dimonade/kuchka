"""Generate `src/kuchka/_api.py`, the names `kuchka` promotes to its top level.

Each leaf module under `kuchka.units` and `kuchka.quantities` owns one hand-written
`__all__`, and that list is the only place a name is typed.
The top-level policy is derived from it:

- every unit constructor (`Volt`, `Tonne`, ...) in `kuchka.units`, which is every
  `__all__` entry that is not an UPPER_CASE unit definition or `*_UNITS` table;
- every quantity type (`Voltage`, `Temperature`, ...) in `kuchka.quantities`, which is
  every `__all__` entry of a leaf module there.

The leaf modules are read with `ast`, so the generator runs even when the generated
file is out of date and would not import.

    uv run python -m tools.generate_api          # rewrite the generated file
    uv run python -m tools.generate_api --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "kuchka"
TARGET = PACKAGE / "_api.py"

HEADER = '''\
"""Names promoted from `kuchka.quantities` and `kuchka.units` to the top level.

Generated by `tools/generate_api.py`; do not edit.
To promote, rename, or remove a name, change the `__all__` of the leaf module that
defines it and run `just generate-api`.
"""

'''


def _all_of(path: Path) -> list[str]:
    """Return the literal `__all__` of the module at `path`."""
    for node in ast.parse(path.read_text()).body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "__all__"
            and isinstance(node.value, ast.List)
        ):
            return [
                element.value
                for element in node.value.elts
                if isinstance(element, ast.Constant) and isinstance(element.value, str)
            ]
    msg = f"{path} has no literal `__all__` list"
    raise SystemExit(msg)


def _leaves(package: Path) -> list[Path]:
    """Return every leaf module under `package`, subpackages included."""
    return sorted(
        path
        for path in package.rglob("*.py")
        if path.name != "__init__.py" and "base" not in path.relative_to(package).parts
    )


def promoted_names() -> tuple[list[str], list[str]]:
    """Return the quantity types and the unit constructors to promote, sorted."""
    quantities = {n for leaf in _leaves(PACKAGE / "quantities") for n in _all_of(leaf)}
    constructors = {
        n
        for leaf in _leaves(PACKAGE / "units")
        for n in _all_of(leaf)
        if not n.isupper()
    }
    return sorted(quantities), sorted(constructors)


def render() -> str:
    """Return the full text of the generated module."""
    quantities, constructors = promoted_names()
    lines = [HEADER.rstrip("\n"), ""]
    lines += [f"from kuchka.quantities import {name}" for name in quantities]
    lines += [f"from kuchka.units import {name}" for name in constructors]
    lines += ["", "__all__ = ["]
    lines += [f'    "{name}",' for name in sorted({*quantities, *constructors})]
    lines += ["]", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the generated module, or with `--check` verify it is current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    arguments = parser.parse_args(argv)
    text = render()
    current = TARGET.read_text() if TARGET.exists() else ""
    if arguments.check:
        if text != current:
            sys.stderr.write(f"{TARGET} is out of date; run `just generate-api`.\n")
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
