"""Rung 4, the unit tables: when the unit arrives apart from the number.

The legacy file keeps its units in the key names, `accepted_voltage_min_mv = -1.000`, so
the number and the unit reach a program as two separate pieces of text.
`parse` reads one piece of text with both in it; this is the case the `*_UNITS` tables
are for.
A table maps the spelling of a unit to the constructor of the quantity, so
`VOLTAGE_UNITS["mV"]` is `Millivolt`, and `VOLTAGE_UNITS["mV"](Decimal("-1.000"))` is
the measurement, with the digits exactly as they were typed.

The migration reads the legacy file that way, and writes the modern one with
`kuchka.wire.dump`, which is the one string that every rung above reads:

    python migrate.py config_legacy.ini > config_modern.toml

It also finds what the convention never checked: a key named for a voltage that carries
a current's suffix has no constructor in the voltage table, and the migration says so
instead of copying the mistake into the new file.
"""

from __future__ import annotations

import sys
from configparser import ConfigParser
from decimal import Decimal
from decimal import InvalidOperation
from pathlib import Path
from typing import Any

from kuchka import wire
from kuchka.units import BAUD_RATE_UNITS
from kuchka.units import CURRENT_UNITS
from kuchka.units import FREQUENCY_UNITS
from kuchka.units import TEMPERATURE_UNITS
from kuchka.units import VOLTAGE_UNITS

# Which table a legacy key belongs to: the physical quantity the name stands for.
TABLES = {
    "accepted_voltage": ("voltage", VOLTAGE_UNITS),
    "accepted_current": ("current", CURRENT_UNITS),
    "accepted_temperature": ("temperature", TEMPERATURE_UNITS),
    "uart_baud_rate": ("baud rate", BAUD_RATE_UNITS),
    "sensor_poll_rate": ("frequency", FREQUENCY_UNITS),
}

# The legacy convention wrote every suffix in lower case, and the tables spell units
# exactly, so the convention needs its own list.
SUFFIXES = {
    "mv": "mV",
    "v": "V",
    "ma": "mA",
    "a": "A",
    "c": "C",
    "k": "K",
    "bd": "Bd",
    "hz": "Hz",
}

EDGES = {"min": "minimum", "max": "maximum"}

HEADER = """\
# Device limits, generated by migrate.py from config_legacy.ini.
#
# Every measurement is one string: a number and its unit.
"""


class MigrationError(Exception):
    """The legacy file holds something that cannot be carried over."""


def _measurement(section: str, key: str, text: str) -> tuple[str, str | None, Any]:
    """Read a legacy entry into its field, its edge if it has one, and its quantity."""
    stem, _, suffix = key.rpartition("_")
    edge: str | None = None
    if stem.endswith(("_min", "_max")):
        stem, _, edge_name = stem.rpartition("_")
        edge = EDGES[edge_name]
    if stem not in TABLES:
        msg = f"{section}.{key}: no quantity is known for {stem!r}"
        raise MigrationError(msg)
    label, table = TABLES[stem]
    spelling = SUFFIXES.get(suffix)
    constructor = None if spelling is None else table.get(spelling)
    if constructor is None:
        msg = f"{section}.{key}: {suffix!r} is not a unit of {label}"
        raise MigrationError(msg)
    try:
        number = Decimal(text)
    except InvalidOperation:
        msg = f"{section}.{key}: {text!r} is not a number"
        raise MigrationError(msg) from None
    return stem, edge, constructor(number)


def read_legacy(text: str) -> dict[str, dict[str, Any]]:
    """Read a legacy file into the quantities of each table of the modern one."""
    parser = ConfigParser()
    parser.read_string(text)
    tables: dict[str, dict[str, Any]] = {}
    for section in parser.sections():
        for key, value in parser.items(section):
            field, edge, quantity = _measurement(section, key, value)
            if edge is None:
                tables.setdefault(section, {})[field] = quantity
            else:
                tables.setdefault(f"{section}.{field}", {})[edge] = quantity
    return tables


def write_modern(tables: dict[str, dict[str, Any]]) -> str:
    """Write the tables as TOML: each measurement is `wire.dump`, one exact string."""
    lines = [HEADER]
    for name, entries in tables.items():
        lines.append(f"[{name}]")
        lines.extend(f'{key} = "{wire.dump(value)}"' for key, value in entries.items())
        lines.append("")
    return "\n".join(lines)


def migrate(text: str) -> str:
    """Turn the text of a legacy file into the text of a modern one."""
    return write_modern(read_legacy(text))


if __name__ == "__main__":
    sys.stdout.write(migrate(Path(sys.argv[1]).read_text(encoding="utf-8")))
