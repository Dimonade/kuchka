"""AC power constructors: volt-amperes for apparent power, vars for reactive.

Apparent power describes the RMS voltage-current product of an AC supply;
reactive power describes the portion exchanged by inductive and capacitive fields.
They share the physical dimension of power, but neither is interchangeable with real
power or with the other quantity.
`kuchka` gives each concept a separate type while keeping the units appropriate to that
concept.

Examples
--------
A small data centre has a 30 kVA UPS.
Its server racks account for 11.5 kVA and its cooling equipment for another 6 kVA.
The remaining apparent-power capacity is:

>>> ups = KilovoltAmpere(30)
>>> servers = KilovoltAmpere(11.5)
>>> cooling = KilovoltAmpere(6)
>>> (ups - servers - cooling).to(KILOVOLT_AMPERE)
12.5 kVA

An industrial motor group has 24 kvar of inductive demand.
A capacitor bank rated at 15 kvar offsets part of that demand, leaving this simplified
residual:

>>> motor_group = Kilovar(24)
>>> capacitor_bank = Kilovar(15)
>>> (motor_group - capacitor_bank).to(KILOVAR)
9 kvar

A fictional orbital shipyard has a 1.2 GVA power-conditioning bus.
Its fabrication lasers reserve 525 MVA, leaving the following apparent-power headroom:

>>> bus = GigavoltAmpere(1.2)
>>> laser_bank = MegavoltAmpere(525)
>>> (bus - laser_bank).to(MEGAVOLT_AMPERE)
675 MVA

Notes
-----
The volt-ampere (VA) is used for `ApparentPower`; the var is used for `ReactivePower`.
The milli- through giga-prefixes are provided for both families.
The var accepts the spellings ``var``, ``VAr``, and ``VAR``; prefixed forms are
generated by the same prefix machinery as the other units.

Both quantities are specialisations of `Power` and can be converted back with
``to_power()``.
That operation changes the quantity's semantic role; it does not calculate real power
from apparent power, determine a power factor, or perform a reactive-power compensation
calculation.
Those require additional electrical data.

Reactive-power signs depend on the convention used by the measurement or application.
The compensation example above therefore treats the load and bank as magnitudes and
subtracts the bank's rating explicitly; it is a planning illustration, not a complete
AC load-flow calculation.

`APPARENT_POWER_UNITS` and `REACTIVE_POWER_UNITS` map unit symbols to their respective
constructors for boundary code that reads unit strings from external sources.

"""

from __future__ import annotations

from typing import TYPE_CHECKING

from kuchka.dimensions import POWER
from kuchka.internal import prefixes
from kuchka.internal.prefixes import with_prefix
from kuchka.internal.unit_table import unit_table
from kuchka.numeric import to_exact
from kuchka.quantities import ApparentPower
from kuchka.quantities import ReactivePower
from kuchka.quantities import UnitDef

if TYPE_CHECKING:
    from collections.abc import Callable
    from collections.abc import Mapping

    from kuchka.numeric import Numeric

VOLT_AMPERE = UnitDef(
    "volt_ampere",
    "VA",
    1,
    POWER,
    words=("volt ampere", "volt-ampere", "voltampere"),
)
MILLIVOLT_AMPERE = with_prefix(prefixes.MILLI, VOLT_AMPERE)
KILOVOLT_AMPERE = with_prefix(prefixes.KILO, VOLT_AMPERE)
MEGAVOLT_AMPERE = with_prefix(prefixes.MEGA, VOLT_AMPERE)
GIGAVOLT_AMPERE = with_prefix(prefixes.GIGA, VOLT_AMPERE)

ApparentPower._canonical_unit = VOLT_AMPERE  # noqa: SLF001 -- this module owns ApparentPower's canonical unit


def VoltAmpere(value: Numeric) -> ApparentPower:
    """Construct an `ApparentPower` from volt-amperes.

    Parameters
    ----------
    value : Numeric
        Apparent power in volt-amperes.

    Returns
    -------
    ApparentPower
        Apparent power represented in volt-amperes.

    Examples
    --------
    A 250 VA instrument transformer supplies two meters drawing 65 VA and 95 VA.
    The unused rating is available for another instrument:

    >>> transformer = VoltAmpere(250)
    >>> meters = VoltAmpere(65) + VoltAmpere(95)
    >>> (transformer - meters).to(VOLT_AMPERE)
    90 VA

    """
    return ApparentPower(to_exact(value) * VOLT_AMPERE.scale, VOLT_AMPERE)


def MillivoltAmpere(value: Numeric) -> ApparentPower:
    """Construct an `ApparentPower` from millivolt-amperes.

    Parameters
    ----------
    value : Numeric
        Apparent power in millivolt-amperes.

    Returns
    -------
    ApparentPower
        Apparent power represented in millivolt-amperes.

    Examples
    --------
    During a low-power AC measurement, a fixture is rated at 8 mVA and the sensor
    module accounts for 3.5 mVA.
    The remaining allowance is:

    >>> fixture_budget = MillivoltAmpere(8)
    >>> sensor_load = MillivoltAmpere(3.5)
    >>> (fixture_budget - sensor_load).to(MILLIVOLT_AMPERE)
    4.5 mVA

    """
    return ApparentPower(to_exact(value) * MILLIVOLT_AMPERE.scale, MILLIVOLT_AMPERE)


